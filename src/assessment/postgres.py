from pathlib import Path
from typing import Any
from uuid import uuid4

from .store import Store


class LeaseLost(ValueError):
    pass


class PgConnection:
    """The narrow DB-API seam shared by the local store and the PostgreSQL worker."""

    def __init__(self, dsn: str):
        try:
            import psycopg
        except ImportError as exc:
            raise ValueError("install PostgreSQL support with uv sync --extra postgres") from exc
        self.raw = psycopg.connect(dsn, autocommit=True, connect_timeout=10)
        self.transaction: Any = None
        with self.raw.transaction():
            self.raw.execute("SELECT pg_advisory_xact_lock(918743992)")
            self.raw.execute("CREATE SCHEMA IF NOT EXISTS assessment")
            self.raw.execute("SET search_path TO assessment, pg_catalog")
            self.raw.execute("""
                CREATE OR REPLACE FUNCTION assessment.json_extract(payload text, path text)
                RETURNS text LANGUAGE sql IMMUTABLE STRICT
                AS $$ SELECT payload::jsonb #>> string_to_array(substring(path from 3), '.') $$
            """)

    def execute(self, sql: str, params=()):
        return self.raw.execute(sql.replace("?", "%s").encode(), params)

    def executemany(self, sql: str, params: Iterable):
        with self.raw.cursor() as cursor:
            cursor.executemany(sql.replace("?", "%s").encode(), params)

    def executescript(self, sql: str):
        script = sql.replace("seq INTEGER PRIMARY KEY", "seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        with self.raw.transaction():
            self.raw.execute("SELECT pg_advisory_xact_lock(918743993)")
            for part in script.split(";"):
                if part.strip():
                    self.raw.execute(part.encode())

    def __enter__(self):
        self.transaction = self.raw.transaction()
        self.transaction.__enter__()
        return self

    def __exit__(self, *exc):
        return self.transaction.__exit__(*exc)

    def close(self):
        self.raw.close()


@dataclass(frozen=True)
class Work:
    key: str
    kind: str
    partition: str
    as_of: str
    token: str
    row_limit: int
    page_limit: int


class PostgresStore(Store):
    def __init__(self, dsn: str, mode: str = "live"):
        self.lease: Work | None = None
        self.connection = PgConnection(dsn)
        try:
            super().__init__(Path(), mode, connection=self.connection)
            self.connection.executescript("""
                CREATE TABLE IF NOT EXISTS tasks (
                    task_key TEXT PRIMARY KEY, kind TEXT NOT NULL, partition TEXT NOT NULL,
                    as_of TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'pending',
                    available_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
                    lease_until TIMESTAMPTZ, lease_token TEXT, attempts INTEGER NOT NULL DEFAULT 0,
                    row_limit INTEGER NOT NULL DEFAULT 1000, page_limit INTEGER NOT NULL DEFAULT 200
                );
                ALTER TABLE tasks ADD COLUMN IF NOT EXISTS row_limit INTEGER NOT NULL DEFAULT 1000;
                ALTER TABLE tasks ADD COLUMN IF NOT EXISTS page_limit INTEGER NOT NULL DEFAULT 200;
                CREATE INDEX IF NOT EXISTS task_availability ON tasks(state, available_at);
                CREATE INDEX IF NOT EXISTS task_partition ON tasks(partition, lease_until);
            """)
        except BaseException:
            with suppress(Exception):
                self.connection.close()
            raise

    def enqueue(self, run_id: str, kind: str, partitions: Iterable[str], as_of: str, *,
                row_limit: int = 1000, page_limit: int = 200) -> int:
        inserted = 0
        with self.connection:
            for partition in partitions:
                inserted += self.connection.execute(
                    """INSERT INTO tasks(task_key,kind,partition,as_of,row_limit,page_limit) VALUES (?,?,?,?,?,?)
                        ON CONFLICT DO NOTHING""",
                    (f"{run_id}:{kind}:{partition}", kind, partition, as_of, row_limit, page_limit),
                ).rowcount
        return inserted

    def claim(self, lease_seconds: int = 90) -> Work | None:
        with self.connection:
            self.connection.execute("""UPDATE tasks SET state='failed'
                WHERE state='leased' AND lease_until <= clock_timestamp() AND attempts >= 5""")
            candidates = self.connection.execute("""SELECT task_key,kind,partition,as_of,row_limit,page_limit FROM tasks
                WHERE available_at <= clock_timestamp() AND attempts < 5 AND
                    (state='pending' OR (state='leased' AND lease_until <= clock_timestamp()))
                ORDER BY available_at,task_key LIMIT 24 FOR UPDATE SKIP LOCKED""").fetchall()
            for key, kind, partition, as_of, row_limit, page_limit in candidates:
                source_key = f"{kind}:{partition}"
                lock = self.connection.execute(
                    "SELECT pg_try_advisory_xact_lock(hashtextextended(?, 0))", (source_key,),
                ).fetchone()
                if not lock or not lock[0]:
                    continue
                busy = self.connection.execute("""SELECT 1 FROM tasks
                    WHERE kind=? AND partition=? AND task_key<>? AND state='leased'
                        AND lease_until > clock_timestamp() LIMIT 1""", (kind, partition, key)).fetchone()
                if busy:
                    continue
                token = uuid4().hex
                self.connection.execute("""UPDATE tasks SET state='leased',lease_token=?,attempts=attempts+1,
                    lease_until=clock_timestamp() + make_interval(secs => ?) WHERE task_key=?""",
                    (token, lease_seconds, key))
                return Work(key, kind, partition, as_of, token, row_limit, page_limit)
        return None

    def renew(self, work: Work, lease_seconds: int = 90) -> bool:
        return self.connection.execute("""UPDATE tasks SET lease_until=clock_timestamp()+make_interval(secs => ?)
            WHERE task_key=? AND lease_token=? AND state='leased' AND lease_until>clock_timestamp()""",
            (lease_seconds, work.key, work.token)).rowcount == 1

    def finish(self, work: Work, success: bool) -> bool:
        return self.connection.execute("""UPDATE tasks SET lease_token=NULL,lease_until=NULL,
            state=CASE WHEN ? THEN 'done' WHEN attempts>=5 THEN 'failed' ELSE 'pending' END,
            available_at=clock_timestamp()+make_interval(secs => 30)
            WHERE task_key=? AND lease_token=? AND state='leased' AND lease_until>clock_timestamp()""",
            (success, work.key, work.token)).rowcount == 1

    def assert_write_lease(self) -> None:
        if (work := self.lease) and not self.connection.execute("""SELECT 1 FROM tasks
            WHERE task_key=? AND lease_token=? AND state='leased' AND lease_until>clock_timestamp() FOR UPDATE""",
            (work.key, work.token)).fetchone():
            raise LeaseLost(f"expired task lease: {work.key}")


def postgres_dsn() -> str:
    if not (dsn := os.getenv("ASSESSMENT_POSTGRES_DSN")):
        raise ValueError("set ASSESSMENT_POSTGRES_DSN in the process environment")
    return dsn
